import os
from PyQt5 import uic
from PyQt5.QtWidgets import QDialog, QFileDialog, QDialogButtonBox, QMessageBox
from PyQt5.QtGui import  QTextDocument
from .qcrocoflow_XML_Management import qcrocoflow_XML_Management

DEFAULTPROJECTNAME = "Default"
DEFAULTPROJECTFILENAME = "project_qcf.xml"
DEFAULTTYPE = "new"

FORM_CLASS, _ = uic.loadUiType(os.path.join(
os.path.dirname(__file__), 'qcrocoflow_XML_project_management_dialog.ui'))
class qcrocoflow_XML_project_management_dialog(QDialog, FORM_CLASS):
    def __init__(self, _fullpathfilename=None, _type=DEFAULTTYPE, parent=None):
        super(qcrocoflow_XML_project_management_dialog, self).__init__(parent)
        self.setupUi(self)
        self.project_file_name = DEFAULTPROJECTFILENAME
        self.project_name = DEFAULTPROJECTNAME
        self.type = _type
        if _fullpathfilename != None and os.path.exists(_fullpathfilename):
            self.project_file_name = _fullpathfilename
        else:
            self.project_file_name = os.path.join(os.path.expanduser("~"), DEFAULTPROJECTFILENAME)
            qcrocoflow_XML_Management().init_xml_file_project(self.project_file_name, self.project_name)
        self.project_Name_List = qcrocoflow_XML_Management().get_list_of_project_in_file(self.project_file_name)
        self.projectFileNameLineEdit.setText(self.project_file_name)
        self.currentProjectFileNameLabel.setText(self.project_file_name)
        self.projectNamesInFileTextEdit.clear()
        for prj in self.project_Name_List:
            self.projectNamesInFileTextEdit.append(prj)

        if self.type == DEFAULTTYPE: # New project
            self.projectFileNameLabel.setText("Project file to store the new project")
            self.projectNameLabel.setText("Define a new project name")
            self.projectNameLineEdit.setText(DEFAULTPROJECTNAME)
            self.projectNamesInFileTextEdit.setEnabled(True)
            self.addProjectToFileButton.setEnabled(True)
        else:
            self.projectFileNameLabel.setText("Project file of the project to open")
            self.projectNameLabel.setText("Select project name")
            self.projectNameLineEdit.setText("")
            self.addProjectToFileButton.setEnabled(False)
            self.projectNamesInFileTextEdit.setEnabled(True)

        self.update_dialog()
        # Connections
        self.selectProjectFileNameButton.clicked.connect(self.select_project_file)
        self.projectFileNameLineEdit.textChanged.connect(self.update_dialog)
        self.projectFileNameLineEdit.editingFinished.connect(self.update_project_file_name)
        self.okcancelButtonBox.accepted.connect(self.ok_button_pressed)
        self.okcancelButtonBox.rejected.connect(self.reject)
        self.projectNamesInFileTextEdit.selectionChanged.connect(self.handleProjectNameSelectionChanged)
        self.addProjectToFileButton.clicked.connect(self.add_project_name)


    def update_project_file_name(self) -> None:
        fullpathprojectfilename = self.projectFileNameLineEdit.text()
        if not os.path.isdir(os.path.dirname(fullpathprojectfilename)):
            QMessageBox.warning(self, "Project file", f"Project file name is not a directory {os.path.dirname(fullpathprojectfilename)}")
            return
        filename = os.path.basename(fullpathprojectfilename)
        if not ".xml" in filename.lower():
            filename += ".xml"
        else:
            filename = filename.split(".")[0] + ".xml"
        self.project_file_name = os.path.join(os.path.dirname(fullpathprojectfilename), filename)
        self.projectFileNameLineEdit.setText(self.project_file_name)

    def handleProjectNameSelectionChanged(self) -> None:
        if self.type == DEFAULTTYPE:  # Do not select existing project name if type is "new"
            return
        text = self.projectNamesInFileTextEdit.textCursor().selectedText()
        self.projectNameLineEdit.setText(text)

    def add_project_name(self) -> None:
        projectnameslist = qcrocoflow_XML_Management().get_list_of_project_in_file(self.projectFileNameLineEdit.text())
        if self.projectNameLineEdit.text() in projectnameslist:
            msgBox = QMessageBox()
            msgBox.setIcon(QMessageBox.Icon.Warning)
            msgBox.setText("Project name \"{self.projectNameLineEdit.text()}\" already exist")
            msgBox.setInformativeText("Do you want to erase it ?")
            msgBox.setStandardButtons(QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No)
            msgBox.setDefaultButton(QMessageBox.StandardButton.No)
            returnValue = msgBox.exec()
            if returnValue == QMessageBox.StandardButton.No:
                return
            if returnValue == QMessageBox.StandardButton.Yes:
                qcrocoflow_XML_Management().remove_project_in_file(self.project_file_name, self.project_name)
                qcrocoflow_XML_Management().add_to_xml_file_project(self.project_file_name, self.project_name)
                self.projectNamesInFileTextEdit.append(self.projectNameLineEdit.text())
        else:
            self.project_name = self.projectNameLineEdit.text()
            self.projectNamesInFileTextEdit.append(self.project_name)
            qcrocoflow_XML_Management().add_to_xml_file_project(self.project_file_name, self.project_name)

    def ok_button_pressed(self) -> None:
        if self.type == DEFAULTTYPE:  # A new project and/or project file is/are to be created
            if self.projectNameLineEdit.text() == "": # Project name cannot be empty
                QMessageBox.warning(self, "Project file", "Project name cannot be empty")
                return
            if self.projectNameLineEdit.text() != self.project_name:  # Ensure to update the project name variable
                self.project_name = self.projectNameLineEdit.text()
            if self.projectFileNameLineEdit.text() == self.project_file_name: # Check if the project file name is new
                qcrocoflow_XML_Management().add_to_xml_file_project(self.project_file_name, self.project_name)
            else:
                self.project_file_name = self.projectFileNameLineEdit.text()
                qcrocoflow_XML_Management().init_xml_file_project(self.project_file_name, self.project_name)
        # Check if user want to use default project name or change it
        #if self.projectNameLineEdit.text() == DEFAULTPROJECTNAME:
        #    if QMessageBox.warning(self, "Project file",
        #                           "Do you want to use default value ?",
        #                           buttons=QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
        #                           defaultButton=QMessageBox.StandardButton.Yes) == QMessageBox.StandardButton.No:
        #        return
        #    else:
        #        self.project_name = DEFAULTPROJECTNAME
        # Check validity of chosen directory (at a minimum). File cannot yet be checked as it can be a new one
        fullpathprojectfilename = self.projectFileNameLineEdit.text()
        if self.type == DEFAULTTYPE:  # A new project file is to be created
            if os.path.isfile(self.projectFileNameLineEdit.text()):
                QMessageBox.warning(self, "Project file",
                                    f"The file {fullpathprojectfilename} exist\nChange the name of the project file")
                return
        if not os.path.isdir(os.path.dirname(self.projectFileNameLineEdit.text())):
            QMessageBox.warning(self, "Project file",
                                   f"{os.path.dirname(self.projectFileNameLineEdit.text())} is not a valid directory")
            return
        self.project_name = self.projectNameLineEdit.text()
        self.project_file_name = self.projectFileNameLineEdit.text()
        self.accept()

    def select_project_file(self) -> None:
        dialog = QFileDialog(self)
        if self.type == DEFAULTTYPE: # A new project file is to be created
            fullpathfilename, _ = dialog.getSaveFileName(self, caption="New project file",
                                            filter="Project (*.XML *.xml)",
                                            directory=os.path.dirname(self.project_file_name),
                                            options=QFileDialog.DontUseNativeDialog|QFileDialog.DontResolveSymlinks)
        else:
            fullpathfilename, _ = dialog.getOpenFileName(self, caption="Open project file",
                                        filter="Project (*.XML *.xml)",
                                        directory=os.path.dirname(self.project_file_name),
                                        options=QFileDialog.DontUseNativeDialog|QFileDialog.DontResolveSymlinks)
        if fullpathfilename:
            """ filename = os.path.basename(fullpathfilename)
            if not "." in filename:
                filename += ".xml"
            else:
                filename = filename.split(".")[0] + ".xml"
            self.project_file_name = os.path.join(os.path.dirname(fullpathfilename), filename) """
            self.project_file_name = fullpathfilename
            self.projectFileNameLineEdit.setText(self.project_file_name)
            self.currentProjectFileNameLabel.setText(self.project_file_name)
            self.update_dialog()

    def update_dialog(self) -> None:
        fullpathprojectfilename = self.projectFileNameLineEdit.text()
        self.currentProjectFileNameLabel.setText("")
        self.projectNamesInFileTextEdit.clear()
        self.projectNameLineEdit.clear()
        if self.type != DEFAULTTYPE:  ######## Open an existing project
            if not os.path.isfile(fullpathprojectfilename):
                QMessageBox.warning(self, "Project file",
                                    f"The file {fullpathprojectfilename} is not a valid project file")
                return
            projectnames = qcrocoflow_XML_Management().get_list_of_project_in_file(fullpathprojectfilename)
            # Fill the list of projects located in the file "fullpathprojectfilename"
            if len(projectnames) > 0:
                for p in projectnames:
                    self.projectNamesInFileTextEdit.append(p)
                self.projectNameLineEdit.setText(projectnames[0])  # Select the first one by default
            self.addProjectToFileButton.setEnabled(False)
        else:     ######## New project name
            if not os.path.isfile(fullpathprojectfilename):
                # self.projectFileNameLineEdit.setText(self.project_file_name)
                self.currentProjectFileNameLabel.setText(fullpathprojectfilename)
                self.projectFileNameLineEdit.setText(fullpathprojectfilename)
                self.projectNameLineEdit.setText(DEFAULTPROJECTNAME)
            else:
                projectnames = qcrocoflow_XML_Management().get_list_of_project_in_file(fullpathprojectfilename)
                # Fill the list of projects located in the file "fullpathprojectfilename"
                if len(projectnames) > 0:
                    for p in projectnames:
                        self.projectNamesInFileTextEdit.append(p)
            self.addProjectToFileButton.setEnabled(True)

    def get_full_path_file_name(self, _extention = True) -> str:
        if _extention:
            return self.project_file_name
        else:
            return self.project_file_name.split(".")[0]

    def get_directory(self) -> str:
        return os.path.dirname(self.project_file_name)

    def get_file_name(self, _extention = True) -> str:
        if _extention:
            return os.path.basename(self.project_file_name)
        else:
            return os.path.basename(self.project_file_name).split(".")[0]
    def get_current_project_name(self) -> str:
        return self.project_name
