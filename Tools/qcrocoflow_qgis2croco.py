    def getNCVariablesWithDim(self, _dataset, _dim: int) -> list:
    # Return a list of variables names with the given dimension
        lVars = list()
        for varname in _dataset.variables:
            var = _dataset.variables[varname]
            if len(var.shape) == _dim:
                lVars.append(varname)
        return lVars

    def GetInformationFromNetCDFFile(self, _file: str) -> list:
    # Create/update widgets of the dialog according variables found"""
        try:
            dataset = nc.Dataset(_file, 'r')
        except:
            QMessageBox.warning(self, "Error", f"Can not open/access file {self.innetCDFFileName}")
            return []
        # Normaly 2D variables have no time dimension
        dVar2D = {"dim":2, "vars":self.getNCVariablesWithDim(dataset, 2)}
        # 3D variables may or not have time dimension
        dVar3D = {"dim":3, "vars":self.getNCVariablesWithDim(dataset, 3)}
        # Normaly all 4D variables have a time dimension
        dVar4D = {"dim":4, "vars":self.getNCVariablesWithDim(dataset, 4)}
        return [dVar2D, dVar3D, dVar4D]

    def onNCVariableComboBoxSelectionChanged(self, index: int) -> None:
        """
        Gère le changement de sélection dans les combobox de variables et met à jour les autres combobox
        
        Args:
            index (int): Index de l'élément sélectionné
        """
        # Récupérer le combobox qui a émis le signal
        current_combo = self.sender()
        dimension = current_combo.accessibleName()
        selected_var = current_combo.currentText()

        # Ignorer la sélection si c'est l'item par défaut
        if selected_var.startswith("(var"):
            if self.netcdfVariableDimensionsGroupBox.layout() is not None:
                cbs = list()
                gbox = self.netcdfVariableDimensionsGroupBox.layout()
                for i in range(gbox.count()):
                    widget = gbox.itemAt(i).widget()
                    if not isinstance(widget, QComboBox):
                        continue
                    if widget.property("Coord") != "lon" or widget.property("Coord") != "lat":
                        cbs.append(widget)
                for c in cbs:
                    c.setEnabled(False)
            self.processChangeButton.setEnabled(False)
            return

        # Sauvegarder la variable sélectionnée
        self.ncCurrentVar = selected_var

        # Récupérer tous les combobox du layout
        layout = self.netcdfVariablesGroupBox.layout()
        all_combos = []
        for i in range(layout.count()):
            widget = layout.itemAt(i).widget()
            if isinstance(widget, QComboBox):
                all_combos.append(widget)
        
        # Mettre à jour les autres combobox selon la sélection actuelle
        for combo in all_combos:
            if combo != current_combo:  # Ne pas modifier le combobox actuel
                combo.currentIndexChanged.disconnect(self.onNCVariableComboBoxSelectionChanged)
                combo.setCurrentIndex(0)
                combo.currentIndexChanged.connect(self.onNCVariableComboBoxSelectionChanged)
        self.printNCVariableInformation()
        self.UpdateDimensionsComboBox()
        return
    
