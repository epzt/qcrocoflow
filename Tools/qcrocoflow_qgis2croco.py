    def getRasterLayerInfo(self) -> list:
        """
        Récupère les informations des couches raster du projet QGIS courant
        
        Returns:
            list: Liste des dictionnaires contenant les informations des couches raster
        """
        self.raster_infos = []
        
        # Récupérer toutes les couches du projet
        layers = QgsProject.instance().mapLayers().values()
        
        # Filtrer et récupérer les informations des couches raster
        for layer in layers:
            if isinstance(layer, QgsRasterLayer):
                layer_info = {
                    'name': layer.name(),                    # Nom de la couche
                    'source': layer.source(),                # Chemin source du fichier
                    'provider': layer.providerType(),        # Type de provider (gdal, etc.)
                    'band_count': layer.bandCount(),         # Nombre de bandes
                    'width': layer.width(),                  # Largeur en pixels
                    'height': layer.height(),                # Hauteur en pixels
                    'crs': layer.crs().authid(),            # Système de coordonnées
                    'extent': layer.extent().toString()      # Emprise de la couche
                }
                self.raster_infos.append(layer_info)

        return self.raster_infos

    def UpdateDimensionsComboBox(self) -> None:
        self.DeleteLayout(self.netcdfVariableDimensionsGroupBox.layout())
        if self.netcdfVariableDimensionsGroupBox.layout() is not None:
            gbox = self.netcdfVariableDimensionsGroupBox.layout()
        else:
            gbox = QHBoxLayout()
        cbs = list()
        cbs.append(QLabel("Lon:", self))
        cbs.append(QComboBox(self))
        cbs.append(QLabel("Lat:", self))
        cbs.append(QComboBox(self))
        if self.ncCurrentVar is None:
            return  # Aucune variable sélectionnée
        try:
            dataset = nc.Dataset(os.path.join(self.currentDirectory, self.innetCDFFileName), 'r')
            if self.ncCurrentVar not in dataset.variables:
                return  # Variable non trouvée dans le dataset
            var = dataset.variables[self.ncCurrentVar]
            dims = var.dimensions
            cbs[1].addItem("(select lon)")
            cbs[1].setProperty("Coord", "lon")
            cbs[3].addItem("(select lat)")
            cbs[3].setProperty("Coord", "lat")
            for dim in dims:
                dim_size = len(dataset.dimensions[dim])
                cbs[1].addItem(f"{dim} ({dim_size})")
                cbs[3].addItem(f"{dim} ({dim_size})")
                # Activer les combobox si la dimension correspond à la taille du raster sélectionné
                if self.currentRasterName is not None:
                    cbs[1].setEnabled(True)
                    cbs[3].setEnabled(True)
                else:
                    cbs[1].setEnabled(False)
                    cbs[3].setEnabled(False)
            # Connexion des signaux après avoir rempli les combobox pour éviter les déclenchements intempestifs
            cbs[1].currentTextChanged.connect(self.onNCDimensionChanged)
            cbs[3].currentTextChanged.connect(self.onNCDimensionChanged)
            gbox.addWidget(cbs[0])
            gbox.addWidget(cbs[1])
            gbox.addWidget(cbs[2])
            gbox.addWidget(cbs[3])
            gbox.addStretch(10)
            self.netcdfVariableDimensionsGroupBox.setLayout(gbox)
            dataset.close()
        except Exception as e:
            QMessageBox.warning(self, "Error", f"Error reading variable dimensions: {str(e)}")
        return

    def getDimensionFromString(self, _str: str) -> str:
        if '(' in _str:
            _str = _str.split('(')[1].strip()
        if ')' in _str:
            _str = _str.split(')')[0].strip()
        return int(_str.strip())

    def onNCDimensionChanged(self, _str: str) -> None:
        """ Create/update the dictionary of dimensions selected for each dimension of the netcdf file
        """
        if _str.startswith("(select"):
            self.ncCoords.pop(self.sender().property("Coord"), None)  # Remove the key if exists
            self.processChangeButton.setEnabled(False)
            return
        for key in self.ncCoords.keys():
            if self.ncCoords[key] == _str:
                QMessageBox.warning(self, "Warning", f"Dimension {_str} already selected for {key}. Please select another one.")
                self.sender().setCurrentIndex(0)
                self.processChangeButton.setEnabled(False)
                return
        self.ncCoords[self.sender().property("Coord")] = _str
        if 'lon' in self.ncCoords:
            for raster in self.raster_infos:
                if raster['name'] == self.currentRasterName:
                    dlon = self.getDimensionFromString(self.ncCoords['lon'])
                    if dlon != raster['width']:
                        QMessageBox.warning(self, "Warning", f"Longitude dimension mismatch: {dlon} != {raster['width']}")
                        self.sender().setCurrentIndex(0)
                        self.processChangeButton.setEnabled(False)
                        return
        if 'lat' in self.ncCoords:
            for raster in self.raster_infos:
                if raster['name'] == self.currentRasterName:
                    dlat = self.getDimensionFromString(self.ncCoords['lat'])
                    if dlat != raster['height']:
                        QMessageBox.warning(self, "Warning", f"Latitude dimension mismatch: {dlat} != {raster['height']}")
                        self.sender().setCurrentIndex(0)
                        self.processChangeButton.setEnabled(False)
                        return
        if len(self.ncCoords) == 2:
            if 'lon' in self.ncCoords and 'lat' in self.ncCoords:
                self.processChangeButton.setEnabled(True)
            else:
                self.processChangeButton.setEnabled(False)
        else:
            self.processChangeButton.setEnabled(False)
        QMessageBox.information(self, "Information", f"{self.ncCoords}")
        return

    def processQGIS2Croco(self) -> None:
        """
        Écrit les données d'un raster QGIS dans une variable NetCDF
        
        Args:
            raster_layer (QgsRasterLayer): La couche raster source
            netcdf_file (str): Chemin du fichier NetCDF
            variable_name (str): Nom de la variable à écraser
        """
        """
        Gère le transfert des données du raster vers le fichier NetCDF
        """
        if self.currentRasterName is None:
            QMessageBox.warning(self, "Warning", "No raster selected")
            return
        if self.ncCurrentVar is None:
            QMessageBox.warning(self, "Warning", "No variable selected")
            return 
        if len(self.ncCoords) != 2 or 'lon' not in self.ncCoords or 'lat' not in self.ncCoords:
            QMessageBox.warning(self, "Warning", "Longitude and Latitude dimensions must be selected")
            return

        # Chercher la couche raster
        for raster in self.raster_infos:
            if raster['name'] == self.currentRasterName:
                # Obtenir la couche depuis le projet
                layers = QgsProject.instance().mapLayersByName(self.currentRasterName)
                if layers:
                    raster_layer = layers[0]
                    break
        if not raster_layer:
            QMessageBox.warning(self, "Warning", "Selected raster layer not found")
            return
        try:
            # Ouvrir le fichier NetCDF en mode modification
            dataset = nc.Dataset(os.path.join(self.currentDirectory, self.innetCDFFileName), 'r+')
            
            # Vérifier que la variable existe
            if self.ncCurrentVar not in dataset.variables:
                raise ValueError(f"Variable {self.ncCurrentVar} not found in {self.innetCDFFileName} file\n{dataset.variables.keys()}")

            # Récupérer la variable
            var = dataset.variables[self.ncCurrentVar]

            # Récupérer les dimensions de la variable
            var_shape = var.shape
            
            # Récupérer les données du raster
            ds = gdal.Open(raster_layer.source())
            if ds is None:
                raise ValueError("Unable to open raster layer with GDAL")
            
            # Créer un bloc pour recevoir les données
            raster_array = ds.GetRasterBand(1).ReadAsArray(0, 0, ds.RasterXSize, ds.RasterYSize)
            # Vérifier si la lecture a réussi
            if raster_array is None:
                raise ValueError("Failed to read raster data")

            # Vérifier l'orientation des coordonnées Y dans le NetCDF
            lat_dim = self.ncCoords['lat'].split(' ')[0]  # Obtenir le nom de la dimension lat
            lat_var = dataset.variables.get(lat_dim)
            
            if lat_var is not None:
                # Vérifier si les latitudes sont dans l'ordre croissant
                lat_values = lat_var[:]
                if lat_values[0] < lat_values[-1]:
                    # Si les latitudes sont croissantes (du sud au nord)
                    # et que le raster est du nord au sud, on inverse
                    raster_array = np.flipud(raster_array)
            else:
                # Si on ne peut pas vérifier, on suppose qu'il faut inverser
                raster_array = np.flipud(raster_array)

            # Vérifier la compatibilité des dimensions
            if raster_array.shape != var_shape[-2:]:  # Compare avec les 2 dernières dimensions
                raise ValueError(f"Raster shape {raster_array.shape} does not match NetCDF variable shape {var_shape}")
            
            # Pour une variable 2D
            if len(var_shape) == 2:
                var[:] = raster_array
                
            # Pour une variable 3D
            elif len(var_shape) == 3:
                for i in range(var_shape[0]-1):
                    var[i, :, :] = raster_array
                
            # Pour une variable 4D
            elif len(var_shape) == 4:
                for i in range(var_shape[0]-1):
                    for j in range(var_shape[1]-1):
                        var[i, j, :, :] = raster_array
                
            # Synchroniser les changements
            dataset.sync()
            
        except Exception as e:
            QMessageBox.critical(self, "Error", f"Failed to write raster to NetCDF: {str(e)}")
            
        finally:
            # Fermer le fichier
            dataset.close()
            QMessageBox.information(self, "Information", f"Raster {self.currentRasterName} data written to variable {self.ncCurrentVar} in {self.innetCDFFileName}")
        return