    def getNCVariableDimensions(self, _varname: str) -> str:
        """
        Récupère les dimensions d'une variable dans le fichier netCDF
        
        Args:
            _varname (str): Nom de la variable
            
        Returns:
            str: Description des dimensions de la variable
        """
        try:
            # Ouvrir le fichier netCDF
            dataset = nc.Dataset(os.path.join(self.currentDirectory, self.innetCDFFileName), 'r')
            # Récupérer la variable
            if _varname not in dataset.variables:
                return "Variable not found in dataset"

            var = dataset.variables[_varname]
            # Récupérer les dimensions
            dims = var.dimensions
            dim_info = []
            # Pour chaque dimension, récupérer son nom et sa taille
            for dim_name in dims:
                dim_size = len(dataset.dimensions[dim_name])
                dim_info.append(f"{dim_name} ({dim_size})")
            # Fermer le fichier
            dataset.close()
            # Retourner la description des dimensions
            return ", ".join(dim_info)   
        except Exception as e:
            return f"Error reading dimensions: {str(e)}"

    def qgis2croco(self) -> None:
        if self.ncCurrentVar is None:
            QMessageBox.warning(self, "Warning", "No variable selected")
            return
        reply = QMessageBox.information(self, "Information", f"Variable {self.ncCurrentVar} will be processed", QMessageBox.Ok | QMessageBox.Cancel,
                               QMessageBox.Cancel)
        if reply == QMessageBox.Ok:
            # L'utilisateur a cliqué sur Ok, on continue le traitement
            self.processQGIS2Croco()
        else:
            # L'utilisateur a cliqué sur Annuler, on arrête le traitement
            return
        return

